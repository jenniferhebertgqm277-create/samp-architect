# Import SAMP Architect engine
sys.path.insert(0, "/root/samp-architect/skills/samp-architect/scripts")
from samp_architect import (
    Building, Vec3, SAMPObject,
    MODULAR_WALL, MODULAR_WALL_WIN, MODULAR_SLAB, MODULAR_SLAB_MED, MODULAR_SLAB_LRG,
    MODULAR_PILLAR_S, MODULAR_PILLAR_R, MODULAR_RAILING,
    GLASS_PANEL, GLASS_STOREFRONT, INTERIOR_DOOR,
    LIGHT_DOWNLIGHT, LIGHT_NEON_BLUE, LIGHT_NEON_GREEN, LIGHT_OMNI,
    TEXTURE_PALETTES, export_to_texture_studio_db, export_to_texture_studio_import, export_pwn_code
)

def build_ls_airport_exterior():
    map_name = "LS_Airport_Exterior"
    # Central terminal entrance anchor point
    origin = Vec3(1680.0, -2285.0, 13.5)
    heading = 0.0

    b = Building(map_name, origin, heading=heading, palette_name="modern_luxury")

    # Dimensions:
    # Terminal Facade runs along North-South (Y axis from -45m to +45m, total length = 90m)
    # Concourse & Canopy extends West (-X axis from 0m to -22m)
    y_min = -42.0
    y_max = 42.0
    y_span = y_max - y_min  # 84 meters

    print(f"[+] Generating Grand Pedestrian Concourse & Sidewalk Plaza...")
    # --------------------------------------------------------------------------
    # 1. LUXURY GRANITE PEDESTRIAN CONCOURSE (Sidewalk along terminal)
    # X from -1.0 to -8.0, Y from -42.0 to +42.0, Z = 0.05 (slightly above asphalt)
    # --------------------------------------------------------------------------
    concourse_w = 7.0
    for y in range(int(y_min), int(y_max), 5):
        for x_off in [-2.5, -6.5]:
            slab = b.add_object_local(MODULAR_SLAB_MED, Vec3(x_off, float(y) + 2.5, 0.05), 0.0, 0.0, 0.0)
            # Polished modern porcelain / granite tiles
            slab.set_material(0, 14668, "711c", "CJ_7_11_TILE", 0)

    # --------------------------------------------------------------------------
    # 2. DROP-OFF ROADWAY PAVING & MARKINGS
    # X from -9.0 to -22.0, Y from -42.0 to +42.0
    # --------------------------------------------------------------------------
    print(f"[+] Generating Drop-Off Lanes & Marked Taxi Stands...")
    for y in range(int(y_min), int(y_max), 5):
        for x_off in [-11.5, -16.5, -21.5]:
            road_slab = b.add_object_local(MODULAR_SLAB_MED, Vec3(x_off, float(y) + 2.5, 0.02), 0.0, 0.0, 0.0)
            road_slab.set_material(0, 9514, "711_sfw", "dt_carpark_line_texture", 0)

    # --------------------------------------------------------------------------
    # 3. MODERN TERMINAL GLASS CURTAIN WALL & ENTRANCE GATES
    # Facade located at X = 0.0 (covering the old terminal wall seamlessly)
    # --------------------------------------------------------------------------
    print(f"[+] Erecting Double-Height Glass Curtain Wall & Automated Entryways...")
    facade_h = 7.0
    y_step = 4.0
    num_glass = int(y_span / y_step)

    for i in range(num_glass):
        y_pos = y_min + (i * y_step) + 2.0
        # Lower glass facade
        g_lower = b.add_object_local(GLASS_STOREFRONT, Vec3(0.0, y_pos, 1.75), 0.0, 0.0, 90.0)
        g_lower.set_material(0, 14668, "711c", "CJ_7_11_win", 0)

        # Upper glass facade
        g_upper = b.add_object_local(GLASS_STOREFRONT, Vec3(0.0, y_pos, 5.25), 0.0, 0.0, 90.0)
        g_upper.set_material(0, 14668, "711c", "CJ_7_11_win", 0)

    # Specific Automated Sliding Glass Entry Portals
    gate_locations = [
        {"y": -28.0, "label": "INTERNATIONAL DEPARTURES", "sub": "GATES 1-12 | CHECK-IN"},
        {"y": -10.0, "label": "DOMESTIC DEPARTURES", "sub": "GATES 13-24 | SECURITY"},
        {"y": 10.0, "label": "VIP & FIRST CLASS LOUNGE", "sub": "PRIORITY ACCESS"},
        {"y": 28.0, "label": "BAGGAGE CLAIM & ARRIVALS", "sub": "GROUND TRANSPORT"}
    ]

    for gate in gate_locations:
        gy = gate["y"]
        # Double sliding glass doors
        b.add_object_local(19856, Vec3(-0.1, gy - 1.2, 1.2), 0.0, 0.0, 90.0)
        b.add_object_local(19856, Vec3(-0.1, gy + 1.2, 1.2), 0.0, 0.0, 270.0)

        # Illuminated Gate Directional Signboard
        sign = b.add_object_local(19475, Vec3(-0.3, gy, 3.8), 0.0, 0.0, 90.0)
        sign.set_material(0, 10101, "2notherbuildsfe", "ws_rooftarmac1", 0xFF0A1428) # Navy backing
        sign_text = f"✈ {gate['label']}\n{gate['sub']}"
        sign.set_material_text(0, sign_text, material_size=64, font="Arial", font_size=32, bold=1, font_color=0xFFFFFFFF, back_color=0xFF0B172A, align=1)

    # --------------------------------------------------------------------------
    # 4. MASSIVE AERODYNAMIC DEPARTURES CANOPY (Spanning Roadway)
    # Height = 7.2m, Width = 22m (from X = 0 to X = -22m), Length = 84m
    # --------------------------------------------------------------------------
    print(f"[+] Constructing Massive Aerodynamic Overhead Canopy...")
    canopy_z = 7.2
    for y in range(int(y_min), int(y_max), 5):
        for x_off in [-2.5, -7.5, -12.5, -17.5, -21.5]:
            canopy_panel = b.add_object_local(MODULAR_SLAB_MED, Vec3(x_off, float(y) + 2.5, canopy_z), 0.0, 0.0, 0.0)
            # Modern dark architectural composite ceiling
            canopy_panel.set_material(0, 14668, "711c", "gun_ceiling1128", 0xFF141923)

    # Structural Heavy Columns supporting the Canopy
    # Row 1: Along the curb (X = -8.5)
    # Row 2: Outer roadway edge (X = -22.0)
    for y in range(int(y_min), int(y_max) + 1, 14):
        # Curb column (Layer 1 + Layer 2 to reach 7m)
        c1_bot = b.add_object_local(MODULAR_PILLAR_S, Vec3(-8.5, float(y), 1.75), 0.0, 0.0, 0.0)
        c1_bot.set_material(0, 10101, "2notherbuildsfe", "ws_rooftarmac1", 0xFF1A2230)
        c1_top = b.add_object_local(MODULAR_PILLAR_S, Vec3(-8.5, float(y), 5.25), 0.0, 0.0, 0.0)
        c1_top.set_material(0, 10101, "2notherbuildsfe", "ws_rooftarmac1", 0xFF1A2230)

        # Outer column
        c2_bot = b.add_object_local(MODULAR_PILLAR_S, Vec3(-22.0, float(y), 1.75), 0.0, 0.0, 0.0)
        c2_bot.set_material(0, 10101, "2notherbuildsfe", "ws_rooftarmac1", 0xFF1A2230)
        c2_top = b.add_object_local(MODULAR_PILLAR_S, Vec3(-22.0, float(y), 5.25), 0.0, 0.0, 0.0)
        c2_top.set_material(0, 10101, "2notherbuildsfe", "ws_rooftarmac1", 0xFF1A2230)

    # --------------------------------------------------------------------------
    # 5. LINEAR NEON ACCENT LIGHTING & SKYLINE ILLUMINATION
    # --------------------------------------------------------------------------
    print(f"[+] Installing Continuous Runway Cyan Neon Contour Lighting...")
    # Continuous Neon along Outer Canopy Fascia (X = -23.5)
    neon_step = 6.0
    num_neons = int(y_span / neon_step)
    for i in range(num_neons):
        ny = y_min + (i * neon_step) + 3.0
        # Outer Edge Neon Cyan
        b.add_object_local(LIGHT_NEON_BLUE, Vec3(-23.5, ny, canopy_z + 0.1), 0.0, 90.0, 0.0)
        # Inner Fascia Neon
        b.add_object_local(LIGHT_NEON_BLUE, Vec3(-0.2, ny, canopy_z + 0.1), 0.0, 90.0, 0.0)

    # Recessed Ceiling Downlights under Canopy for bright night visibility
    for y in range(int(y_min) + 3, int(y_max), 8):
        # Downlight over Sidewalk
        b.add_object_local(LIGHT_DOWNLIGHT, Vec3(-4.5, float(y), canopy_z - 0.1), 0.0, 0.0, 0.0)
        # Downlight over Drop-off Lane 1
        b.add_object_local(LIGHT_DOWNLIGHT, Vec3(-12.0, float(y), canopy_z - 0.1), 0.0, 0.0, 0.0)
        # Downlight over Outer Lane
        b.add_object_local(LIGHT_DOWNLIGHT, Vec3(-18.5, float(y), canopy_z - 0.1), 0.0, 0.0, 0.0)

    # --------------------------------------------------------------------------
    # 6. GIANT MAIN AIRPORT ILLUMINATED MONUMENT SIGN
    # Centered above Terminal Center (X = -0.5, Y = 0.0, Z = 8.5)
    # --------------------------------------------------------------------------
    print(f"[+] Creating Grand Monumental Airport Signage...")
    main_sign = b.add_object_local(19475, Vec3(-0.5, 0.0, 9.2), 0.0, 0.0, 90.0)
    main_sign.set_material(0, 10101, "2notherbuildsfe", "ws_rooftarmac1", 0xFF060D1A)
    main_sign.set_material_text(
        0,
        "LOS SANTOS INTERNATIONAL AIRPORT\n★ ★ ★ ★ ★   TERMINAL 1   ★ ★ ★ ★ ★",
        material_size=128, font="Impact", font_size=42, bold=1, font_color=0xFFFFFFFF, back_color=0xFF0B172A, align=1
    )

    # --------------------------------------------------------------------------
    # 7. FLIGHT INFORMATION DISPLAY SYSTEM (FIDS Outdoor Board)
    # Located at Main Pedestrian Entrance (X = -7.5, Y = 0.0)
    # --------------------------------------------------------------------------
    print(f"[+] Placing Live Flight Information Display Boards (FIDS)...")
    fids_board = b.add_object_local(19475, Vec3(-7.5, 0.0, 3.2), 0.0, 0.0, 90.0)
    fids_board.set_material(0, 10101, "2notherbuildsfe", "ws_rooftarmac1", 0xFF080B12)
    fids_text = (
        "LIVE DEPARTURES | LSX AIRPORT\n"
        "FLIGHT   DESTINATION   TIME   GATE   STATUS\n"
        "LC-101   LIBERTY CITY  08:30   A01   ON TIME\n"
        "SF-204   SAN FIERRO    08:45   B03   BOARDING\n"
        "LV-509   LAS VENTURAS  09:10   A04   ON TIME\n"
        "VC-880   VICE CITY     09:40   C02   ON TIME"
    )
    fids_board.set_material_text(0, fids_text, material_size=96, font="Courier New", font_size=20, bold=1, font_color=0xFF33DD11, back_color=0xFF080B12, align=0)

    # --------------------------------------------------------------------------
    # 8. STREET FURNITURE, PALMS, BOLLARDS, SEATING & LUGGAGE CARTS
    # --------------------------------------------------------------------------
    print(f"[+] Adding Pedestrian Amenities, Bollards, Planters & Palm Trees...")
    # Safety Bollards along Curb (X = -8.3)
    for y in range(int(y_min) + 1, int(y_max), 3):
        b.add_object_local(1237, Vec3(-8.3, float(y), 0.5), 0.0, 0.0, 0.0)

    # Passenger Benches & Luggage Trolley Stations
    for y in [-35.0, -20.0, 20.0, 35.0]:
        # Stainless Steel / Wooden Modern Bench
        bench = b.add_object_local(1280, Vec3(-6.8, float(y), 0.4), 0.0, 0.0, 90.0)
        # Airport Luggage Trolleys
        b.add_object_local(3658, Vec3(-6.8, float(y) + 3.0, 0.4), 0.0, 0.0, 0.0)
        b.add_object_local(3658, Vec3(-6.8, float(y) + 4.2, 0.4), 0.0, 0.0, 0.0)

    # Decorative Planter Boxes with Palms along Sidewalk
    for y in [-38.0, -18.0, 18.0, 38.0]:
        # Square concrete planter base
        planter = b.add_object_local(MODULAR_SLAB, Vec3(-4.0, float(y), 0.2), 0.0, 0.0, 0.0)
        planter.set_material(0, 10101, "2notherbuildsfe", "Bow_church_grass_alt", 0)
        # Tall Elegant Palm
        b.add_object_local(712, Vec3(-4.0, float(y), 0.4), 0.0, 0.0, 0.0)

    # --------------------------------------------------------------------------
    # 9. VIP AIRPORT EXECUTIVE LIMOUSINE & TAXI RANK
    # --------------------------------------------------------------------------
    # Taxi Stand Dispatch Booth / Kiosk
    kiosk = b.add_object_local(MODULAR_WALL, Vec3(-10.5, -38.0, 1.75), 0.0, 0.0, 90.0)
    kiosk.set_material(0, 9514, "711_sfw", "mono1_sfe", 0xFF0D1B2A)
    kiosk_sign = b.add_object_local(19475, Vec3(-10.6, -38.0, 3.2), 0.0, 0.0, 90.0)
    kiosk_sign.set_material_text(0, "TAXI & VIP VALET\nDISPATCH", material_size=32, font="Arial", font_size=24, bold=1, font_color=0xFFFFFF00, back_color=0xFF000000, align=1)

    # --------------------------------------------------------------------------
    # EXPORTING
    # --------------------------------------------------------------------------
    print(f"\n[✓] LS Airport Exterior Mapping Complete! Total Objects: {len(b.objects)}")

    # 1. Export directly to Texture Studio SQLite SavedMaps
    db_file = export_to_texture_studio_db(b)
    print(f"[✓] Saved to Texture Studio Database: {db_file}")

    # 2. Export to Texture Studio ImportMaps (.pwn)
    pwn_file = export_to_texture_studio_import(b)
    print(f"[✓] Saved to Texture Studio ImportMaps: {pwn_file}")

    # 3. Export standalone .pwn script for server gamemodes
    standalone_path = "/root/texture-studio-bobi/scriptfiles/LS_Airport_Exterior_Standalone.pwn"
    with open(standalone_path, "w", encoding="utf-8") as f:
        f.write(export_pwn_code(b, streamer=True))
    print(f"[✓] Saved Standalone PAWN Code: {standalone_path}")

    return b

if __name__ == "__main__":
    build_ls_airport_exterior()
